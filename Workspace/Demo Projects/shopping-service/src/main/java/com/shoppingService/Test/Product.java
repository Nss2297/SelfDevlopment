package com.shoppingService.Test;

public class Product {

	int a;
	String b;
	float c;

	public int getA() {
		return a;
	}

	public void setA(int a) {
		this.a = a;
	}

	public String getB() {
		return b;
	}

	public void setB(String b) {
		this.b = b;
	}

	public float getC() {
		return c;
	}

	public void setC(float c) {
		this.c = c;
	}

	public Product(int a, String b, float c) {
		super();
		this.a = a;
		this.b = b;
		this.c = c;
	}

}
