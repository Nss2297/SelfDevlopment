CREATE TABLE PBM_BUSINESS_RULES.POLICY_ENDORSEMENT
(
	POLICY_ENDORSEMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    POLICY_INFORMATION_ID NUMBER NOT NULL,
    ENDORSEMENT_NUMBER VARCHAR2(50),
    ENDORSEMENT_DATE DATE,
    ENDORSEMENT_TYPE VARCHAR2(100),
    ENDORSEMENT_MESSAGE VARCHAR2(1000),
    CONSTRAINT PK_POLICY_ENDORSEMENT PRIMARY KEY (POLICY_ENDORSEMENT_ID),
    CONSTRAINT FK_PE_POLICY_INFORMATION_ID
  	  FOREIGN KEY (POLICY_INFORMATION_ID) REFERENCES PBM_BUSINESS_RULES.POLICY_INFORMATION (POLICY_INFORMATION_ID),
  	CONSTRAINT UK_POLICY_ENDORSEMENT UNIQUE (POLICY_INFORMATION_ID,ENDORSEMENT_NUMBER)
