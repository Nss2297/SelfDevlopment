    BENEFIT_CODE  VARCHAR2(30) NOT NULL,
    BENEFIT_DESCRIPTION VARCHAR2(250) NOT NULL,
    BENEFIT_LIMIT_VALUE NUMBER NOT NULL,
    BENEFIT_LIMIT_CURRENCY VARCHAR2(30)NOT NULL,
