CREATE TABLE PBM_BUSINESS_RULES.POLICY_CLASSES
(
	POLICY_CLASS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    POLICY_INFORMATION_ID NUMBER NOT NULL,
    CLASS_CODE  VARCHAR2(50) NOT NULL,
    CLASS_LIMIT_VALUE NUMBER,
    CLASS_LIMIT_CURRENCY  VARCHAR2(30),
    COVERAGE VARCHAR2(2500),
    EXCLUSION VARCHAR2(2500),
    COMMENTS VARCHAR2(3000),
    CONSTRAINT PK_POLICY_CLASSES PRIMARY KEY (POLICY_CLASS_ID),
    CONSTRAINT FK_POLICY_CLASSES_POLICY_INFORMATION_ID
    	FOREIGN KEY (POLICY_INFORMATION_ID) REFERENCES PBM_BUSINESS_RULES.POLICY_INFORMATION (POLICY_INFORMATION_ID),
    CONSTRAINT UK_POLICY_CLASSES UNIQUE (POLICY_INFORMATION_ID,CLASS_CODE)
);