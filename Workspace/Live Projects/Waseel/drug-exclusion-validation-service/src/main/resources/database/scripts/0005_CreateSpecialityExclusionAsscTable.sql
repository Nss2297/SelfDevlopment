CREATE TABLE PBM_BUSINESS_RULES.SPECIALITY_EXCLUSION_ASSC
(
	SPECIALITY_EXCLUSION_ASSC_ID NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
	SPECIALITY_ID NUMBER NOT NULL,
	EXCLUSION_ID NUMBER NOT NULL,
	LAST_UPDATE_DATE DATE NOT NULL,
	IS_ENABLED  CHAR(1) DEFAULT ('1') NOT NULL,
	CONSTRAINT PK_SEASSC_SEASS_ID PRIMARY KEY (SPECIALITY_EXCLUSION_ASSC_ID),
	CONSTRAINT UK_SPECIALITY_EXCLUSION_ASSC UNIQUE (SPECIALITY_ID,EXCLUSION_ID),
	CONSTRAINT FK_SEASSC_SPECIALITY_ID
    	FOREIGN KEY (SPECIALITY_ID) REFERENCES PBM_BUSINESS_RULES.SPECIALITY (SPECIALITY_ID),
    CONSTRAINT FK_SEASSC_EXCLUSION_ID
    	FOREIGN KEY (EXCLUSION_ID) REFERENCES PBM_BUSINESS_RULES.DRUG_EXCLUSION_METADATA (EXCLUSION_ID)
);
